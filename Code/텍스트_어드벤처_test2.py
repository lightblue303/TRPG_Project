# 2. 공통 행동 규칙
# 플레이어의 행동을 확인하고, 게임 규칙에 맞게 처리하기 위한 함수들

import random


# 2-1. 주사위 굴리기
# 지정된 면수의 주사위를 굴려 결과를 반환한다.
def roll_dice(sides=20):
    return random.randint(1, sides)


# 2-2. 행동 판정
# 주사위 결과와 보정치를 더해 난이도(DC) 이상인지 판단한다.
def check_action(dc, modifier=0):
    roll = roll_dice(20)
    total = roll + modifier

    return {
        "roll": roll,
        "total": total,
        "success": total >= dc
    }


# 2-3. 체력 변경
# 피해나 회복을 적용하되, 체력이 0 미만이나 최대 체력을 넘지 않게 한다.
def change_hp(player, amount):
    player["hp"] = max(
        0,
        min(player["max_hp"], player["hp"] + amount)
    )
    return player["hp"]


# 2-4. 아이템 획득
# 플레이어의 인벤토리에 아이템을 추가한다.
def get_item(player, item):
    player["items"].append(item)
    return player["items"]


# 2-5. 아이템 사용
# 보유한 아이템만 사용할 수 있으며, 사용하면 인벤토리에서 제거한다.
def use_item(player, item):
    if item in player["items"]:
        player["items"].remove(item)
        return True

    return False


# 2-6. 소지금 변경
# 구매나 보상에 따라 소지금을 변경하고, 돈이 부족하면 거래를 거부한다.
def change_gold(player, amount):
    if player["gold"] + amount < 0:
        return False

    player["gold"] += amount
    return True


# 2-7. 조건 플래그 설정
# 특정 행동이나 사건을 완료했을 때 게임 상태에 기록한다.
def set_flag(state, flag):
    state["flags"].add(flag)


# 2-8. 조건 충족 확인
# 필요한 플래그가 설정되어 있는지 확인한다.
def has_flag(state, flag):
    return flag in state["flags"]


# 2-9. 장면 이동
# 이동 조건을 확인한 뒤 현재 장면 번호를 변경한다.
def change_scene(state, next_scene, required_flag=None):
    if required_flag is not None:
        if not has_flag(state, required_flag):
            return False

    state["scene"] = next_scene
    return True


# 2-10. 플레이어 초기 상태
# 게임 시작 시 플레이어의 체력, 소지금, 아이템을 설정한다.
def create_player(hp=20, gold=50):
    return {
        "hp": hp,
        "max_hp": hp,
        "gold": gold,
        "items": []
    }


# 2-11. 게임 상태 초기화
# 현재 장면과 조건 플래그를 저장하는 기본 상태를 만든다.
def create_game_state():
    return {
        "scene": 1,
        "flags": set()
    }

"""## 3. 게임 상태와 시나리오 연결"""

# 기존 장면 데이터와 공통 행동 규칙을 연결한다.
# 단서 획득, 조건부 선택지, 장면 이동을 처리한다.


def play_with_state():
    # 3-1. 게임 시작 상태 설정
    state = create_game_state()
    state["scene"] = 0  # 기존 시나리오는 0번 장면부터 시작
    player = create_player()

    game_over = False

    print("《잠긴 종》 게임을 시작합니다.")

    # 3-2. 게임 진행 반복
    while not game_over:
        scene_id = state["scene"]
        current = scenes[scene_id]

        print("\n" + "=" * 40)
        print(current["title"])
        print("=" * 40)
        print(current["story"])

        # 3-3. 현재 장면의 선택지 준비
        choices = list(current["choices"])

        # 금속 조각을 가지고 있다면 추가 선택지 제공
        if scene_id == 5 and "금속 조각" in player["items"]:
            choices.append(
                ("금속 조각으로 잠금장치를 살펴본다.", 8)
            )

        print("\n[소지품]", player["items"])

        for i, (text, _) in enumerate(choices, start=1):
            print(f"{i}. {text}")

        print("0. 게임 종료")

        # 3-4. 플레이어 입력 확인
        answer = input("\n선택 번호: ").strip()

        if answer == "0":
            print("게임을 종료합니다.")
            break

        if not answer.isdigit():
            print("숫자를 입력해 주세요.")
            continue

        choice_number = int(answer)

        if not 1 <= choice_number <= len(choices):
            print("없는 선택지입니다.")
            continue

        selected_text, next_scene = choices[choice_number - 1]

        print(f"\n[행동] {selected_text}")

        # 3-5. 단서 획득 처리
        # 7번 장면에서 금속 조각을 챙기거나 조사하면 획득
        if scene_id == 7 and choice_number in (1, 2):
            if "금속 조각" not in player["items"]:
                get_item(player, "금속 조각")
                set_flag(state, "found_metal_fragment")
                print("[획득] 금속 조각을 얻었습니다!")

        # 3-6. 장면 이동 처리
        if change_scene(state, next_scene):
            print(f"[이동] {scene_id} -> {state['scene']}")
        else:
            print("[이동 실패] 조건을 충족하지 못했습니다.")

        # 3-7. 게임 종료 조건
        if state["scene"] == 8:
            print("\n첫 장의 이야기가 끝났습니다.")
            print("최종 소지품:", player["items"])
            game_over = True


# 실행
